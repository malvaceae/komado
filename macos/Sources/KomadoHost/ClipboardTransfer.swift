import AppKit
import KomadoCore

/// Call only after the authenticated session and route have been checked.
@MainActor
final class ClipboardTransfer {
    private enum Preparation { case manual, automatic }
    private let pasteboard: NSPasteboard
    private var prepared: (until: TimeInterval, mode: Preparation)?
    private var lastRequest: TimeInterval?
    private var automatic = false
    private var automaticChangeCount: Int?
    private static let excludedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("com.apple.is-remote-clipboard"),
    ]

    init(pasteboard: NSPasteboard = .general) { self.pasteboard = pasteboard }

    func stopAutomatic() {
        automatic = false; automaticChangeCount = nil
        if prepared?.mode == .automatic { prepared = nil }
    }

    func reset() { prepared = nil; lastRequest = nil; stopAutomatic() }

    func execute(_ operation: ClipboardRequest.Operation, allowed: Bool, busy: Bool,
                 automaticAllowed: Bool = false,
                 now: TimeInterval = ProcessInfo.processInfo.systemUptime) -> ClipboardResponse.Result {
        guard allowed, now.isFinite else { reset(); return .unavailable }
        let isAutomatic: Bool
        switch operation {
        case .autoStart, .autoPoll, .autoPrepare, .autoSet: isAutomatic = true
        default: isAutomatic = false
        }
        if isAutomatic && !automaticAllowed { stopAutomatic(); return .unavailable }
        let isSet: Bool
        switch operation {
        case .set, .autoSet: isSet = true
        default: isSet = false
        }
        if isSet {
            let expected: Preparation = isAutomatic ? .automatic : .manual
            let valid = prepared.map { now <= $0.until && $0.mode == expected } ?? false
            prepared = nil
            guard valid, !isAutomatic || automatic else { return .unavailable }
        } else {
            prepared = nil
        }
        let rateLimited = !isSet && (lastRequest.map { now - $0 < 0.2 } ?? false)
        lastRequest = now
        guard !busy, !rateLimited else { return .busy }
        switch operation {
        case .prepare:
            prepared = (now + 10, .manual)
            return .ready
        case .autoStart:
            automatic = true
            automaticChangeCount = pasteboard.changeCount
            return .started
        case .autoPrepare:
            guard automatic else { return .unavailable }
            prepared = (now + 10, .automatic)
            return .ready
        case .get:
            let before = pasteboard.changeCount
            guard let value = readText(automatic: false), before == pasteboard.changeCount else { return .unavailable }
            if automatic { automaticChangeCount = before }
            return .text(value)
        case .autoPoll:
            guard automatic, let previous = automaticChangeCount else { return .unavailable }
            let before = pasteboard.changeCount
            guard before != previous else { return .unchanged }
            let value = readText(automatic: true)
            guard before == pasteboard.changeCount else { return .busy }
            automaticChangeCount = before
            return value.map { .text($0) } ?? .unchanged
        case let .set(value), let .autoSet(value):
            guard ClipboardCodec.validText(value) else { return .unavailable }
            pasteboard.clearContents()
            guard pasteboard.setString(value, forType: .string) else { return .unavailable }
            if automatic { automaticChangeCount = pasteboard.changeCount }
            return .ok
        }
    }

    private func readText(automatic: Bool) -> String? {
        guard let items = pasteboard.pasteboardItems, items.count == 1, let item = items.first,
              !item.types.contains(.fileURL),
              !item.types.contains(NSPasteboard.PasteboardType("NSFilenamesPboardType")) else { return nil }
        if automatic {
            let types = Set(item.types).union(pasteboard.types ?? [])
            guard types.isDisjoint(with: Self.excludedTypes) else { return nil }
        }
        guard let value = item.string(forType: .string), ClipboardCodec.validText(value) else { return nil }
        return value
    }
}
